def write_reliability_diagram() -> None:
    rows = read_csv(RESULTS / "claims.csv")
    confs = np.array([float(r["score"]) for r in rows])
    correct = np.array([int(r["supported"]) for r in rows])
    n_bins = 10
    bin_edges = np.linspace(0.0, 1.0, n_bins + 1)
    xs, ys, counts = [], [], []
    for i in range(n_bins):
        mask = (confs >= bin_edges[i]) & (confs < bin_edges[i + 1] if i < n_bins - 1 else confs <= 1.0)
        if mask.sum() == 0:
            continue
        xs.append(float(np.mean(confs[mask])))
        ys.append(float(np.mean(correct[mask])))
        counts.append(int(mask.sum()))
    fig, ax = plt.subplots(figsize=(4.6, 4.2))
    ax.plot([0, 1], [0, 1], linestyle="--", color="gray", linewidth=1, label="perfect")
    ax.plot(xs, ys, marker="o", color="#1f77b4", linewidth=1.5, label="HealGen claims")
    for x, y, n in zip(xs, ys, counts):
        ax.annotate(str(n), (x, y), textcoords="offset points", xytext=(4, 4), fontsize=7)
    ax.set_xlabel("Confidence (support score)")
    ax.set_ylabel("Empirical support rate")
    ax.set_xlim(0, 1)
    ax.set_ylim(0, 1)
    ax.legend(loc="upper left", fontsize=8)
    ax.set_title("Reliability diagram (all claims, 4 systems)", fontsize=9)
    fig.tight_layout()
    out = PAPER_FIGURES / "reliability_diagram.png"
    fig.savefig(out, dpi=200)
    plt.close(fig)
    print(f"Wrote {out}")


def write_latency_retrieval_figure() -> None:
    rows = read_csv(RESULTS / "system_summary.csv")
    order = {"vanilla": 0, "rag": 1, "cove": 2, "healgen": 3}
    rows.sort(key=lambda r: order.get(r["system"], 99))
    labels = [r["system"] for r in rows]
    lat = [float(r["mean_latency_s"]) for r in rows]
    calls = [float(r["mean_bm25_calls"]) for r in rows]
    x = np.arange(len(labels))
    fig, ax1 = plt.subplots(figsize=(5.4, 3.4))
    bars = ax1.bar(x, lat, width=0.55, color="#4c78a8", label="mean latency (s)")
    ax1.set_ylabel("Mean latency (s)")
    ax1.set_xticks(x)
    ax1.set_xticklabels(labels)
    ax2 = ax1.twinx()
    ax2.plot(x, calls, marker="s", color="#e45756", linewidth=1.8, label="BM25 calls")
    ax2.set_ylabel("Mean BM25 calls")
    for b, v in zip(bars, lat):
        ax1.annotate(f"{v:.2f}", (b.get_x() + b.get_width() / 2, v), ha="center", fontsize=7)
    handles1, labels1 = ax1.get_legend_handles_labels()
    handles2, labels2 = ax2.get_legend_handles_labels()
    ax1.legend(handles1 + handles2, labels1 + labels2, fontsize=8, loc="upper left")
    ax1.set_title("Cost profile per system", fontsize=9)
    fig.tight_layout()
    out = PAPER_FIGURES / "latency_retrieval.png"
    fig.savefig(out, dpi=200)
    plt.close(fig)
    print(f"Wrote {out}")


def write_headline_macros() -> None:
    """Emit paper/tables/headline.tex: \\newcommand macros sourced from CSVs.

    The abstract/prose may only state measured values through these macros so
    every number traces back to results/system_summary.csv / ablations.csv.
    """
    summary = read_csv(RESULTS / "system_summary.csv")
    by_sys = {r["system"]: r for r in summary}
    abl_rows = read_csv(RESULTS / "ablations.csv")

    def fmt(v: str) -> str:
        return f"{float(v):.3f}"

    lines = [
        "% Auto-generated by make_tables.py -- DO NOT HAND-EDIT.",
        "% Sources: results/system_summary.csv, results/ablations.csv",
    ]
    macro_map = [
        ("SPVanilla", "vanilla", "sp_macro"),
        ("SPRAG", "rag", "sp_macro"),
        ("SPCoVe", "cove", "sp_macro"),
        ("SPHealGen", "healgen", "sp_macro"),
        ("SPGoldVanilla", "vanilla", "sp_macro_goldonly"),
        ("SPGoldRAG", "rag", "sp_macro_goldonly"),
        ("SPGoldCoVe", "cove", "sp_macro_goldonly"),
        ("SPGoldHealGen", "healgen", "sp_macro_goldonly"),
        ("SPMicroHealGen", "healgen", "sp_micro"),
        ("HRHealGen", "healgen", "hallucination_rate"),
        ("AnyHRHealGen", "healgen", "any_hallucination_rate"),
        ("EMHealGen", "healgen", "em"),
        ("EMRAG", "rag", "em"),
        ("FscoreHealGen", "healgen", "f1"),
        ("RetrHealGen", "healgen", "mean_bm25_calls"),
        ("LatHealGen", "healgen", "mean_latency_s"),
        ("ECEHealGen", "healgen", "ece"),
    ]
    for macro, system, col in macro_map:
        if system not in by_sys:
            sys.exit(f"ERROR: system '{system}' missing from system_summary.csv")
        lines.append(f"\\newcommand{{\\{macro}}}{{{fmt(by_sys[system][col])}}}")

    n_abl = len({r["qid"] for r in abl_rows})
    lines.append(f"\\newcommand{{\\NAbl}}{{{n_abl}}}")
    lines.append(f"\\newcommand{{\\NTest}}{{{by_sys['healgen']['n_examples']}}}")

    out = PAPER_TABLES / "headline.tex"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {out}")


def main() -> None:
    PAPER_TABLES.mkdir(parents=True, exist_ok=True)
    PAPER_FIGURES.mkdir(parents=True, exist_ok=True)

    write_headline_macros()
    write_main_results_table()
    write_efficiency_table()
    write_pairwise_table()
    write_ablation_table()
    write_tau_table()
    judge_csv = export_judge_validation_csv()
    write_judge_table(judge_csv)
    write_reliability_diagram()
    write_latency_retrieval_figure()
    print("\nAll tables and figures generated from results files.")


if __name__ == "__main__":
    main()
