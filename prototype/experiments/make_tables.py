def write_pairwise_table() -> None:
    rows = read_csv(RESULTS / "pairwise_tests.csv")
    lines = [
        "% Auto-generated by make_tables.py from results/pairwise_tests.csv",
        "\\begin{tabular}{l c c c}",
        "\\toprule",
        "Comparison ($SP_{macro}$) & $\\Delta$ & raw $p$ & Holm $p$ \\\\",
        "\\midrule",
    ]
    for r in rows:
        comparison = r["comparison"].replace("healgen", "HealGen").replace("cove", "CoVe")
        comparison = comparison.replace("rag", "RAG").replace("vanilla", "Vanilla")
        star = ""
        try:
            if float(r["adjusted_p_value"]) < 0.05:
                star = "$^{*}$"
        except ValueError:
            pass
        lines.append(
            f"{comparison} & {r['delta']} & {r['raw_p_value']} & {r['adjusted_p_value']}{star} \\\\"
        )
    lines += ["\\bottomrule", "\\end{tabular}", ""]
    out = PAPER_TABLES / "pairwise_tests.tex"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {out}")


def write_ablation_table() -> None:
    abl_rows = read_csv(RESULTS / "ablations.csv")
    main_rows = read_csv(RESULTS / "main.csv")

    def agg(rows: list[dict[str, str]]) -> dict[str, float]:
        sp = [float(r["sp_macro"]) for r in rows]
        return {
            "n": len(rows),
            "sp_macro": float(np.mean(sp)) if sp else 0.0,
            "hallucination_rate": float(
                np.mean([int(r["any_hallucination"]) for r in rows])
            )
            if rows
            else 0.0,
            "em": float(np.mean([float(r["em"]) for r in rows])) if rows else 0.0,
            "f1": float(np.mean([float(r["f1"]) for r in rows])) if rows else 0.0,
            "mean_bm25_calls": float(np.mean([float(r["num_bm25_calls"]) for r in rows]))
            if rows
            else 0.0,
        }

    healgen_rows = [r for r in main_rows if r["system"] == "healgen"]
    groups: dict[str, list[dict[str, str]]] = {"healgen": healgen_rows}
    for r in abl_rows:
        groups.setdefault(r["system"], []).append(r)

    lines = [
        "% Auto-generated by make_tables.py from results/ablations.csv + results/main.csv",
        "\\begin{tabular}{l c c c c c}",
        "\\toprule",
        "Variant & SP$_{macro}$ & Any-HR & EM & F1 & BM25 calls \\\\",
        "\\midrule",
    ]
    labels = {
        "healgen": "\\textbf{HealGen (full)}",
        "healgen-noCRE": "w/o CRE (uniform risk)",
        "healgen-noAESP": "w/o AESP (always retrieve)",
        "healgen-noLSHE": "w/o LSHE (hedge only)",
    }
    for key in ("healgen", "healgen-noCRE", "healgen-noAESP", "healgen-noLSHE"):
        if key not in groups:
            sys.exit(f"ERROR: ablation group '{key}' missing from results")
        a = agg(groups[key])
        lines.append(
            f"{labels[key]} & {a['sp_macro']:.3f} & {a['hallucination_rate']:.3f} & "
            f"{a['em']:.3f} & {a['f1']:.3f} & {a['mean_bm25_calls']:.1f} \\\\"
        )
    lines += ["\\bottomrule", "\\end{tabular}", ""]
    out = PAPER_TABLES / "ablation.tex"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {out}")


