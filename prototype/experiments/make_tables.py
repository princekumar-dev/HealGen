def read_csv(path: Path) -> list[dict[str, str]]:
    if not path.exists():
        sys.exit(f"ERROR: required results file missing: {path}")
    with path.open("r", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def read_tau_rows() -> list[dict[str, str]]:
    """Read tau_sensitivity.csv with a plausibility tripwire.

    The committed full-dev sweep is n=154.  A test-suite bug once clobbered
    this file with a 4-item fixture (test_tau_deterministic without
    output_path; fixed) -- refuse fixture-scale input here so a rebuild can
    never emit n=4 rows into the paper instead of failing loudly.
    """
    rows = read_csv(RESULTS / "tau_sensitivity.csv")
    if not rows:
        sys.exit("ERROR: tau_sensitivity.csv is empty")
    for r in rows:
        try:
            n = int(r["n"])
        except (KeyError, ValueError):
            sys.exit(f"ERROR: tau_sensitivity.csv row missing/invalid n: {r}")
        if n < 100:
            sys.exit(
                f"ERROR: tau_sensitivity.csv n={n} < 100 -- fixture-scale "
                "input; restore the committed sweep (git checkout -- "
                "prototype/results/tau_sensitivity.csv) before regenerating "
                "tables"
            )
    return rows


def export_judge_validation_csv() -> Path:
    """Programmatic JSON -> CSV export (no hand-copied values)."""
    src = RESULTS / "judge_validation.json"
    if not src.exists():
        sys.exit(f"ERROR: required results file missing: {src}")
    data = json.loads(src.read_text(encoding="utf-8"))
    dst = RESULTS / "judge_validation.csv"
    rows = []
    for key in ("judge1", "judge2"):
        j = data[key]
        rows.append(
            {
                "role": key,
                "model": j["model"],
                "accuracy": j["accuracy"],
                "auc": j["auc"],
                "n": j["n"],
                "primary": str(key == data.get("primary_selected", "")).lower()
                if data.get("primary_selected") == j["model"]
                else "false",
                "gate_threshold_auc": data.get("gate_threshold_auc", ""),
                "gate_passed": str(data.get("gate_passed", "")).lower(),
            }
        )
    # primary flag: match by model id (primary_selected stores the model id)
    for r in rows:
        r["primary"] = str(r["model"] == data.get("primary_selected")).lower()
    with dst.open("w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)
    print(f"Exported {len(rows)} rows -> {dst}")
    return dst


