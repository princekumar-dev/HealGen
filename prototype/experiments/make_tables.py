"""Generate paper tables + result figures from results CSVs only (Task 16).

Honesty rule (design §4): no result value is ever written by hand. Every cell in
every \\input{} table traces to a results/*.csv column, produced by the experiment
scripts. The judge-validation JSON is exported to CSV programmatically first so
the table path is CSV -> .tex like all others.

Outputs:
- paper/tables/main_results.tex     (system_summary.csv)
- paper/tables/pairwise_tests.tex   (pairwise_tests.csv)
- paper/tables/ablation.tex         (ablations.csv + main.csv reference row)
- paper/tables/tau_sensitivity.tex  (tau_sensitivity.csv)
- paper/tables/judge_validation.tex (judge_validation.csv, exported from JSON)
- paper/figures/reliability_diagram.png (claims.csv)
- paper/figures/latency_retrieval.png   (system_summary.csv)
"""

from __future__ import annotations

import csv
import json
from pathlib import Path
import sys

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

PROTOTYPE_ROOT = Path(__file__).resolve().parents[1]
if str(PROTOTYPE_ROOT) not in sys.path:
    sys.path.insert(0, str(PROTOTYPE_ROOT))

from healgen import config  # noqa: E402

RESULTS = config.PATHS["results"]
REPO_ROOT = PROTOTYPE_ROOT.parent
PAPER_TABLES = REPO_ROOT / "paper" / "tables"
PAPER_FIGURES = REPO_ROOT / "paper" / "figures"


def read_csv(path: Path) -> list[dict[str, str]]:
    if not path.exists():
        sys.exit(f"ERROR: required results file missing: {path}")
    with path.open("r", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def export_judge_validation_csv() -> Path:
    """Programmatic JSON -> CSV export (no hand-copied values)."""
    src = RESULTS / "judge_validation.json"
    if not src.exists():
        sys.exit(f"ERROR: required results file missing: {src}")
    data = json.loads(src.read_text(encoding="utf-8"))
    dst = RESULTS / "judge_validation.csv"
    rows = []
    for key in ("judge1", "judge2"):
        j = data[key]
        rows.append(
            {
                "role": key,
                "model": j["model"],
                "accuracy": j["accuracy"],
                "auc": j["auc"],
                "n": j["n"],
                "primary": str(key == data.get("primary_selected", "")).lower()
                if data.get("primary_selected") == j["model"]
                else "false",
                "gate_threshold_auc": data.get("gate_threshold_auc", ""),
                "gate_passed": str(data.get("gate_passed", "")).lower(),
            }
        )
    # primary flag: match by model id (primary_selected stores the model id)
    for r in rows:
        r["primary"] = str(r["model"] == data.get("primary_selected")).lower()
    with dst.open("w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)
    print(f"Exported {len(rows)} rows -> {dst}")
    return dst


def write_main_results_table() -> None:
    rows = read_csv(RESULTS / "system_summary.csv")
    order = {"vanilla": 0, "rag": 1, "cove": 2, "healgen": 3}
    rows.sort(key=lambda r: order.get(r["system"], 99))
    lines = [
        "% Auto-generated by make_tables.py from results/system_summary.csv",
        "\\begin{tabular}{l c c c c c c c c}",
        "\\toprule",
        "System & SP$_{macro}$ [95\\% CI] & SP$_{micro}$ & SP$_{gold}$ & HR & Any-HR & EM & F1 & ECE \\\\",
        "\\midrule",
    ]
    names = {"vanilla": "Vanilla", "rag": "RAG", "cove": "CoVe", "healgen": "\\textbf{HealGen}"}
    for r in rows:
        ci = f"[{r['sp_macro_ci_lo']}, {r['sp_macro_ci_hi']}]"
        lines.append(
            f"{names.get(r['system'], r['system'])} & {r['sp_macro']} {ci} & "
            f"{r['sp_micro']} & {r.get('sp_macro_goldonly', '')} & {r['hallucination_rate']} & {r['any_hallucination_rate']} & "
            f"{r['em']} & {r['f1']} & {r['ece']} \\\\"
        )
    lines += ["\\bottomrule", "\\end{tabular}", ""]
    out = PAPER_TABLES / "main_results.tex"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {out}")


